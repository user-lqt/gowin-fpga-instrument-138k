"""Repack existing integer HDL tables as synchronous ROM; never refit values."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1] / "rtl/audio_core"


def main():
    frequencies = {
        int(index): int(value)
        for index, value in re.findall(
            r"7'd\s*(\d+)\s*:\s*fc\s*=\s*32'd\s*(\d+)",
            (ROOT / "note_to_fc.v").read_text(encoding="utf-8"))
    }
    periods = {
        int(index): int(value)
        for index, value in re.findall(
            r"7'd\s*(\d+)\s*:\s*period_q16\s*=\s*48'd\s*(\d+)",
            (ROOT / "note_to_period.v").read_text(encoding="utf-8"))
    }
    fractions = {
        int(index): (int(ratio), int(reciprocal))
        for index, ratio, reciprocal in re.findall(
            r"8'd(\d+): begin ratio=17'd(\d+); reciprocal=17'd(\d+); end",
            (ROOT / "pitch_fraction_rom.v").read_text(encoding="utf-8"))
    }
    assert set(frequencies) == set(periods) == set(range(128))
    assert set(fractions) == set(range(256))
    assert max(periods.values()) < 1 << 29
    lines = [
        "// Generated by tools/generate_pitch_lookup.py from exact existing tables.",
        "module pitch_lookup_sync(",
        "    input wire clk,input wire [6:0] note_id,input wire [7:0] fraction,",
        "    output wire [31:0] fc,output wire [47:0] period_q16,",
        "    output wire [16:0] ratio,reciprocal);",
        "    reg [60:0] note_rom[0:127];",
        "    reg [33:0] fraction_rom[0:255];",
        "    reg [60:0] note_word;",
        "    reg [33:0] fraction_word;",
        "    initial begin",
    ]
    for index in range(128):
        word = (frequencies[index] << 29) | periods[index]
        lines.append(f"        note_rom[{index}]=61'h{word:016x};")
    for index in range(256):
        ratio, reciprocal = fractions[index]
        word = (ratio << 17) | reciprocal
        lines.append(f"        fraction_rom[{index}]=34'h{word:09x};")
    lines += [
        "    end",
        "    always @(posedge clk) begin",
        "        note_word<=note_rom[note_id];",
        "        fraction_word<=fraction_rom[fraction];",
        "    end",
        "    assign fc=note_word[60:29];",
        "    assign period_q16={19'd0,note_word[28:0]};",
        "    assign {ratio,reciprocal}=fraction_word;",
        "endmodule",
    ]
    (ROOT / "pitch_lookup_sync.v").write_text("\n".join(lines) + "\n", encoding="ascii")
    print("Generated exact 128-note / 256-fraction synchronous pitch ROM")


if __name__ == "__main__":
    main()
